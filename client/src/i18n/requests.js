const HOUR = 60 * 60 * 1000;
const DAY = 24 * HOUR;

// Same wording rules as utils/requests timeLeft(), but translated: "in 5 hours", "2 days overdue"
export function timeLeftText(t, v, now = Date.now()) {
  if (!v) return "";
  const diff = new Date(v).getTime() - now;
  const abs = Math.abs(diff);
  let time;
  if (abs < HOUR) time = t("mins", { count: Math.max(Math.round(abs / 60000), 1) });
  else if (abs < DAY) time = t("hours", { count: Math.round(abs / HOUR) });
  else time = t("days", { count: Math.round(abs / DAY) });
  return t(diff >= 0 ? "timeIn" : "timeOverdue", { time });
}

